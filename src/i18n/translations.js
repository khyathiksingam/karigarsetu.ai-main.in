export const rtlLanguages = new Set(['ur', 'ks', 'sd']);

export const isSupportedLanguage = (language) => Boolean(language && translations[language]);

export const getLanguageConfig = (language = 'en') => {
  const code = isSupportedLanguage(language) ? language : 'en';
  const option = LANGUAGE_OPTIONS.find((item) => item.code === code) || LANGUAGE_OPTIONS[0];
  return {
    code,
    native: option.native,
    english: option.english,
    dir: rtlLanguages.has(code) ? 'rtl' : 'ltr',
  };
};

export const getTranslation = (language = 'en', key = '') => {
  const safeKey = String(key || '').trim();
  const resolvedLanguage = isSupportedLanguage(language) ? language : 'en';
  const dict = translations[resolvedLanguage] || translations.en;
  const segments = safeKey.split('.').filter(Boolean);

  let value = dict;
  for (const segment of segments) {
    if (value && typeof value === 'object' && segment in value) {
      value = value[segment];
    } else {
      value = undefined;
      break;
    }
  }

  const directValue = dict[safeKey] || (Array.isArray(segments) && segments.length === 1 ? dict[segments[0]] : undefined);
  const fallback = directValue ?? value ?? (translations.en[segments[0]] ?? translations.en[segments.join('.')]);

  if (typeof fallback === 'string' && fallback.trim()) {
    return fallback;
  }

  const englishFallback = safeKey.includes('.')
    ? safeKey.split('.').reduce((acc, part) => acc && acc[part], translations.en)
    : translations.en[safeKey];

  return englishFallback || safeKey || 'Text';
};
