export function searchLocations(query) {
    const clean = query.trim().toLowerCase();
    if (clean.length < 2)
        return [];
    return POPULAR_INDIAN_LOCATIONS.filter((loc) => {
        return (loc.city.toLowerCase().includes(clean) ||
            loc.state.toLowerCase().includes(clean) ||
            (loc.craftContext && loc.craftContext.toLowerCase().includes(clean)));
    }).slice(0, 8); // Top 8 relevant matches
}
/**
 * Reverse geocode latitude & longitude to Indian City and State
 */
export async function reverseGeocodeCoords(lat, lon) {
    try {
        // OpenStreetMap Nominatim API (free, reliable with timeout)
        const controller = new AbortController();
        const timeoutId = setTimeout(() => controller.abort(), 4000);
        const response = await fetch(`https://nominatim.openstreetmap.org/reverse?format=json&lat=${lat}&lon=${lon}&zoom=10&addressdetails=1`, {
            headers: {
                'Accept-Language': 'en',
                'User-Agent': 'KarigarSetuAI-App',
            },
            signal: controller.signal,
        });
        clearTimeout(timeoutId);
        if (response.ok) {
            const data = await response.json();
            const addr = data.address || {};
            const city = addr.city ||
                addr.town ||
                addr.village ||
                addr.county ||
                addr.state_district ||
                '';
            const state = addr.state || '';
            if (city || state) {
                return {
                    city,
                    state,
                    district: addr.county || addr.state_district || '',
                    postalCode: addr.postcode || '',
                };
            }
        }
    }
    catch (err) {
        console.warn('Network reverse geocode failed', err);
    }
    return null;
}
